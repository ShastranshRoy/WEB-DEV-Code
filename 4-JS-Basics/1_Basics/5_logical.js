/*
Types of logical operation

&& -> and
|| -> or
!  -> reverse

*/

let isLoggedin = true;
let isPaid = false;

console.log(isLoggedin && isPaid);          // And gives true if both the values are true, else false

let isEmailUser = true;
let isGoogleUser = false;

console.log(isEmailUser || isGoogleUser);   // OR gives true result if any one is true.

